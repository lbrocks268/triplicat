/* Bradford: standard curve (linear or quadratic) and sample concentrations. */
(function(){
  'use strict';
  var TK = window.TK, UI = window.TKUI, el = UI.el, last = null;

  // Synthetic demo values (not measured data).
  var DEMO_STD = 'conc\tA1\tA2\tA3\n0\t0.052\t0.049\t0.055\n0.025\t0.098\t0.104\t0.093\n0.05\t0.146\t0.139\t0.151\n0.1\t0.236\t0.247\t0.229\n0.2\t0.418\t0.401\t0.432\n0.4\t0.741\t0.772\t0.753\n';
  var DEMO_SMP = 'sample\tdilution\tA1\tA2\tA3\nLysate\t20\t0.512\t0.498\t0.531\nFlow-through\t10\t0.301\t0.287\t0.312\nElution 1\t5\t0.622\t0.641\t0.609\nElution 2\t5\t0.884\t0.902\t0.871\n';

  function readStd(){
    var t = TK.parseTable(el('in').value), x = [], y = [], levels = {};
    t.rows.forEach(function(r){
      var c = TK.toNum(r[0], t.delim); if(!isFinite(c)) return;
      for(var j = 1; j < r.length; j++){ var a = TK.toNum(r[j], t.delim); if(isFinite(a)){ x.push(c); y.push(a); levels[c] = 1; } }
    });
    return { x: x, y: y, levels: Object.keys(levels).length };
  }
  function readSmp(){
    var t = TK.parseTable(el('in2').value), dil = -1, out = [];
    t.header.forEach(function(h, i){ if(i > 0 && /^(dil|verd|df$|factor|faktor)/i.test(h)) dil = i; });
    t.rows.forEach(function(r, k){
      var A = [], d = 1;
      for(var j = 1; j < r.length; j++){
        var v = TK.toNum(r[j], t.delim);
        if(j === dil){ if(isFinite(v) && v > 0) d = v; } else if(isFinite(v)) A.push(v);
      }
      // a first column that is itself a number counts as an absorbance, not as a name
      var first = TK.toNum(r[0], t.delim), name = r[0];
      if(isFinite(first) && dil !== 0){ A.unshift(first); name = 'Sample ' + (k + 1); }
      if(A.length) out.push({ name: name || ('Sample ' + (k + 1)), dil: d, A: A });
    });
    return out;
  }
  // Concentration for an absorbance on the fitted curve
  function invert(fit, a, quad, cmax){
    var b = fit.coef;
    if(!quad) return (a - b[0]) / b[1];
    if(Math.abs(b[2]) < 1e-14) return (a - b[0]) / b[1];
    var disc = b[1] * b[1] - 4 * b[2] * (b[0] - a);
    if(disc < 0) return NaN;
    var r1 = (-b[1] + Math.sqrt(disc)) / (2 * b[2]), r2 = (-b[1] - Math.sqrt(disc)) / (2 * b[2]);
    var ok = [r1, r2].filter(function(r){ return r >= -0.05 * cmax && r <= 1.5 * cmax; });
    if(!ok.length) return Math.abs(r1) < Math.abs(r2) ? r1 : r2;
    return Math.min.apply(null, ok);       // the root on the rising branch
  }

  function rscript(s, quad, unit, smp){
    return '# Bradford standard curve, generated by the analysis toolkit\n' +
      'std <- data.frame(\n  conc = c(' + s.x.join(', ') + '),\n  A    = c(' + s.y.join(', ') + ')\n)\n' +
      'fit <- lm(A ~ conc' + (quad ? ' + I(conc^2)' : '') + ', data = std)\nsummary(fit)\n\n' +
      (smp.length ? 'samples <- data.frame(\n  sample   = c(' + smp.map(function(m){ return JSON.stringify(m.name); }).join(', ') + '),\n' +
        '  dilution = c(' + smp.map(function(m){ return m.dil; }).join(', ') + '),\n  A        = c(' + smp.map(function(m){ return TK.mean(m.A); }).join(', ') + ')\n)\nb <- coef(fit)\n' +
        (quad ? 'samples$conc <- sapply(samples$A, function(a) { r <- Re(polyroot(c(b[1] - a, b[2], b[3]))); min(r[r >= 0]) }) * samples$dilution\n'
              : 'samples$conc <- (samples$A - b[1]) / b[2] * samples$dilution\n') + 'samples   # concentration in ' + unit + '\n\n' : '') +
      'plot(std$conc, std$A, xlab = "Protein / ' + unit + '", ylab = "A595", pch = 16)\n' +
      'grid <- data.frame(conc = seq(0, max(std$conc), length.out = 200))\nlines(grid$conc, predict(fit, grid), lwd = 2)\n';
  }

  function run(){
    var s = readStd(), smp = readSmp(), quad = el('m_quad').checked, unit = el('u_c').value || 'mg/mL';
    var plotBox = el('out_plot'), res = el('out_res'), nt = el('out_notes');
    last = null; el('dl').hidden = true;
    if(!el('in').value.trim()){
      plotBox.innerHTML = '<div class="empty">Paste your standards or load the demo data to see the curve.</div>'; res.innerHTML = ''; nt.innerHTML = ''; return;
    }
    var need = quad ? 4 : 3;
    if(s.levels < need){
      plotBox.innerHTML = '<div class="empty">At least ' + need + ' standard concentrations are needed for this model.</div>'; res.innerHTML = '';
      nt.innerHTML = UI.notes([{ warn: true, text: 'Could read ' + s.x.length + ' absorbance values at ' + s.levels + ' concentrations. Expected: first column concentration, further columns absorbance (one column per replicate).' }]); return;
    }
    var fit = TK.polyfit(s.x, s.y, quad ? 2 : 1);
    if(!fit){ plotBox.innerHTML = '<div class="empty">No curve could be fitted to these standards.</div>'; res.innerHTML = ''; nt.innerHTML = ''; return; }
    var cmax = Math.max.apply(null, s.x), cmin = Math.min.apply(null, s.x), gx = [], gy = [];
    for(var i = 0; i <= 200; i++){ var c = cmax * i / 200; gx.push(c); gy.push(fit.predict(c)); }
    var aLo = Math.min(fit.predict(cmin), fit.predict(cmax)), aHi = Math.max(fit.predict(cmin), fit.predict(cmax));
    var rows = [], px = [], py = [], n = [], outside = 0;
    smp.forEach(function(m){
      var a = TK.mean(m.A), c = invert(fit, a, quad, cmax), flag = '';
      if(a > aHi){ flag = 'above range'; outside++; } else if(a < aLo){ flag = 'below range'; outside++; }
      m.mean = a; m.conc = c; m.final = c * m.dil; m.flag = flag;
      if(isFinite(c)){ px.push(c); py.push(a); }
      rows.push([UI.esc(m.name), TK.sig(a, 4), m.A.length > 1 ? TK.sig(TK.sd(m.A), 2) : '—', m.A.length, TK.sig(c, 4), TK.sig(m.dil, 4),
                 '<b>' + TK.sig(m.final, 4) + '</b>', flag ? '<span class="flag">' + flag + '</span>' : 'ok']);
    });
    var spec = { xlabel: 'Protein / ' + unit, ylabel: 'A595', zeroX: true, legend: true, legendLeft: true,
      series: [{ kind: 'line', x: gx, y: gy, color: 0, label: quad ? 'Quadratic fit' : 'Linear fit' },
               { kind: 'points', x: s.x, y: s.y, color: 7, label: 'Standards', hollow: true }].concat(
               px.length ? [{ kind: 'points', x: px, y: py, color: 2, label: 'Samples (as measured)', r: 5 }] : []) };
    UI.applyLabels(spec);
    plotBox.innerHTML = UI.plot(spec);
    var b = fit.coef, term = function(v, tail){ return (v < 0 ? ' − ' : ' + ') + TK.sig(Math.abs(v), 4) + tail; };
    var eq = 'A = ' + TK.sig(b[0], 4) + term(b[1], ' · c') + (quad ? term(b[2], ' · c²') : '');
    res.innerHTML = '<div class="kv"><span>' + eq + '</span><span>R² <b>' + fit.r2.toFixed(4) + '</b></span><span>Standards <b>' + s.levels + '</b></span><span>Points <b>' + fit.n + '</b></span></div>' +
      (rows.length ? UI.table(['Sample', 'Mean A', 'SD', 'n', 'Measured / ' + UI.esc(unit), 'Dilution', 'Result / ' + UI.esc(unit), 'Range'], rows, 'res')
                   : '<div class="calc-hint" style="margin-top:10px">Add samples in the second field to get their concentrations.</div>');
    if(b[1] <= 0) n.push({ warn: true, text: 'The curve does not rise with concentration. Are the concentration and absorbance columns swapped?' });
    if(outside) n.push({ warn: true, text: outside + ' sample(s) lie outside the absorbance range covered by the standards. Those values are extrapolated: dilute or concentrate and measure again.' });
    if(fit.r2 < 0.98) n.push({ warn: true, text: 'R² is below 0.98. Check the standards for outliers before trusting the sample values.' });
    if(!quad && fit.r2 < 0.995 && s.levels >= 4) n.push({ text: 'Bradford curves flatten at higher concentrations. If the points bend away from the line, try the quadratic model or use a narrower concentration range.' });
    n.push({ text: 'Least-squares fit through all individual standard readings, including the blank at 0 (no blank subtraction beforehand). Result = concentration read from the curve × dilution factor.' });
    nt.innerHTML = UI.notes(n);
    last = { spec: spec, fit: fit, s: s, smp: smp, quad: quad, unit: unit }; el('dl').hidden = false;
  }

  UI.wire({ run: run, demo: function(){ el('in').value = DEMO_STD; el('in2').value = DEMO_SMP; },
    actions: {
      svg: function(){ if(last) UI.downloadSVG('bradford.svg', last.spec); },
      png: function(){ if(last) UI.downloadPNG('bradford.png', last.spec); },
      csv: function(){ if(!last) return;
        var rows = [['sample', 'mean_A', 'sd_A', 'n', 'measured_' + last.unit, 'dilution', 'result_' + last.unit, 'range']];
        last.smp.forEach(function(m){ rows.push([m.name, m.mean, m.A.length > 1 ? TK.sd(m.A) : '', m.A.length, m.conc, m.dil, m.final, m.flag || 'ok']); });
        rows.push([]); rows.push(['model', last.quad ? 'quadratic' : 'linear']); rows.push(['coefficients'].concat(last.fit.coef)); rows.push(['R2', last.fit.r2]);
        UI.downloadText('bradford-results.csv', UI.csv(rows), 'text/csv'); },
      r: function(){ if(last) UI.downloadText('bradford.R', rscript(last.s, last.quad, last.unit, last.smp)); }
    } });
})();
