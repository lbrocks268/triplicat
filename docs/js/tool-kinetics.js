/* Enzyme kinetics: Michaelis-Menten fit. */
(function(){
  'use strict';
  var TK = window.TK, UI = window.TKUI, el = UI.el, last = null;

  // Synthetic demo values (not measured data).
  var DEMO = 'S\tv1\tv2\tv3\n0.05\t0.71\t0.66\t0.74\n0.1\t1.34\t1.25\t1.41\n0.25\t2.79\t2.95\t2.71\n0.5\t4.71\t4.44\t4.63\n' +
             '1\t6.52\t6.89\t6.61\n2\t8.83\t8.51\t9.02\n4\t10.05\t10.41\t9.87\n8\t11.42\t11.03\t11.31\n';

  // Readings the user unticked, keyed "row:column" of the pasted table
  var ex = UI.exclusions();

  function read(){
    var t = TK.parseTable(el('in').value), S = [], v = [], xS = [], xv = [], bad = 0, levels = {}, grid = [], width = 0;
    ex.sync(t.header.length + '#' + t.rows.map(function(r){ return r[0]; }).join('|'));
    t.rows.forEach(function(r, i){
      var s = TK.toNum(r[0], t.delim);
      if(!isFinite(s)){ bad++; return; }
      var row = { label: r[0], cells: [] };
      for(var j = 1; j < r.length; j++){
        var y = TK.toNum(r[j], t.delim), k = i + ':' + j;
        if(!isFinite(y)){ row.cells.push(null); continue; }
        row.cells.push({ key: k, text: r[j], off: ex.off(k) });
        if(ex.off(k)){ xS.push(s); xv.push(y); } else { S.push(s); v.push(y); levels[s] = 1; }
      }
      width = Math.max(width, r.length - 1); grid.push(row);
    });
    var head = ['[S]'];
    for(var j = 1; j <= width; j++) head.push(UI.esc(/^col\d+$/.test(t.header[j] || 'col') ? 'Rep ' + j : t.header[j]));
    return { S: S, v: v, xS: xS, xv: xv, bad: bad, levels: Object.keys(levels).length, grid: grid, head: head };
  }
  function gridHtml(d){ return d.grid.length ? UI.pointGrid('Rates', d.head, d.grid) : ''; }

  function rscript(d, su, vu){
    return '# Michaelis-Menten fit, generated by the analysis toolkit\n' +
      'd <- data.frame(\n  S = c(' + d.S.join(', ') + '),\n  v = c(' + d.v.join(', ') + ')\n)\n' +
      (d.xS.length ? '# left out in the toolkit (S, v): ' + d.xS.map(function(s, i){ return '(' + s + ', ' + d.xv[i] + ')'; }).join(', ') + '\n' : '') + '\n' +
      'fit <- nls(v ~ Vmax * S / (Km + S), data = d,\n           start = list(Vmax = max(d$v) * 1.2, Km = median(d$S)))\n' +
      'summary(fit)\n\n# 95 % confidence intervals (estimate ± t * SE, as shown in the toolkit)\nco <- summary(fit)$coefficients\ntq <- qt(0.975, df.residual(fit))\ncbind(lower = co[, 1] - tq * co[, 2], upper = co[, 1] + tq * co[, 2])\n\n' +
      'grid <- data.frame(S = seq(0, max(d$S), length.out = 200))\n' +
      'plot(d$S, d$v, xlab = "[S] / ' + su + '", ylab = "v / ' + vu + '", pch = 16)\n' +
      'lines(grid$S, predict(fit, grid), lwd = 2)\n';
  }

  function run(){
    var d = read(), su = el('u_s').value || 'mM', vu = el('u_v').value || 'U/mg';
    var plotBox = el('out_plot'), res = el('out_res'), nt = el('out_notes');
    last = null; el('dl').hidden = true;
    if(!el('in').value.trim()){
      plotBox.innerHTML = '<div class="empty">Paste your data or load the demo data to see the fit.</div>'; res.innerHTML = ''; nt.innerHTML = ''; return;
    }
    if(d.S.length < 3 || d.levels < 3){
      plotBox.innerHTML = '<div class="empty">At least three substrate concentrations with a rate are needed.</div>'; res.innerHTML = gridHtml(d);
      nt.innerHTML = UI.notes([{ warn: true, text: 'Could read ' + d.S.length + ' data points at ' + d.levels + ' concentrations. Expected: first column substrate concentration, further columns rates (one column per replicate).' + UI.exampleHint() }]);
      return;
    }
    var fit = TK.mmFit(d.S, d.v);
    if(fit.error || !isFinite(fit.Vmax) || !isFinite(fit.Km)){
      plotBox.innerHTML = '<div class="empty">The fit did not work with these values.</div>'; res.innerHTML = gridHtml(d);
      nt.innerHTML = UI.notes([{ warn: true, text: fit.error || 'No finite parameters were found.' }]); return;
    }
    var smax = Math.max.apply(null, d.S.concat(d.xS)), smaxFit = Math.max.apply(null, d.S), gx = [], gy = [];
    for(var i = 0; i <= 200; i++){ var s = smax * i / 200; gx.push(s); gy.push(TK.mmModel(s, fit.params)); }
    var spec = { xlabel: '[S] / ' + su, ylabel: 'v / ' + vu, zeroX: true, zeroY: true, legend: true, legendBottom: true,
      series: [{ kind: 'line', x: gx, y: gy, color: 0, label: 'Michaelis-Menten fit' }, { kind: 'points', x: d.S, y: d.v, color: 7, label: 'Data', hollow: true }]
        .concat(d.xS.length ? [{ kind: 'points', x: d.xS, y: d.xv, color: 5, cross: true, label: 'Left out' }] : []),
      vlines: fit.Km > 0 && fit.Km < smax ? [{ x: fit.Km, color: 0, label: 'Km' }] : [] };
    UI.applyLabels(spec);
    plotBox.innerHTML = UI.plot(spec);
    var pm = function(k){ return TK.sig(fit.params[k]) + ' ± ' + TK.sig(fit.se[k], 2); };
    var ci = function(k){ return TK.sig(fit.ci[k][0], 3) + ' to ' + TK.sig(fit.ci[k][1], 3); };
    res.innerHTML = UI.table(['Parameter', 'Estimate ± SE', '95 % CI', 'Unit'], [
      ['V<sub>max</sub>', pm(0), ci(0), UI.esc(vu)], ['K<sub>m</sub>', pm(1), ci(1), UI.esc(su)]], 'res') +
      '<div class="kv"><span>R² <b>' + fit.r2.toFixed(4) + '</b></span><span>Residual SE <b>' + TK.sig(fit.sigma, 3) + '</b></span><span>Points <b>' + fit.n + '</b></span><span>Concentrations <b>' + d.levels + '</b></span></div>' + gridHtml(d);
    var n = [];
    if(!fit.converged) n.push({ warn: true, text: 'The fit did not converge cleanly. Treat the parameters with caution.' });
    if(fit.Km <= 0 || fit.Vmax <= 0) n.push({ warn: true, text: 'A parameter is not positive. The data do not follow Michaelis-Menten kinetics, or columns are swapped.' });
    if(fit.Km > 0 && smaxFit < 2 * fit.Km) n.push({ warn: true, text: 'The highest substrate concentration (' + TK.sig(smaxFit) + ' ' + UI.esc(su) + ') is below 2 × K<sub>m</sub>. Saturation is not reached, so V<sub>max</sub> and K<sub>m</sub> are poorly determined. Measure at higher concentrations.' });
    if(fit.Km > 0 && Math.min.apply(null, d.S.filter(function(s){ return s > 0; })) > fit.Km) n.push({ warn: true, text: 'No substrate concentration lies below K<sub>m</sub>. The rising part of the curve is not covered.' });
    if(fit.se[1] / Math.abs(fit.Km) > 0.5) n.push({ warn: true, text: 'The standard error of K<sub>m</sub> is more than half of its value.' });
    if(d.levels < 6) n.push({ text: 'Only ' + d.levels + ' substrate concentrations. Six to eight, spread around K<sub>m</sub>, give a more reliable fit.' });
    if(d.xS.length) n.push({ text: d.xS.length + ' reading(s) left out of the fit, shown as crosses. Say so in your methods.' });
    if(d.bad) n.push({ text: d.bad + ' row(s) without a numeric substrate concentration were skipped.' });
    n.push({ text: 'Nonlinear least squares on all individual points that are ticked, v = V<sub>max</sub> · [S] / (K<sub>m</sub> + [S]). Confidence intervals are estimate ± t · SE. Substrate inhibition or cooperativity are not modelled.' });
    nt.innerHTML = UI.notes(n);
    last = { spec: spec, fit: fit, d: d, su: su, vu: vu }; el('dl').hidden = false;
  }

  UI.wire({ run: run, demo: function(){ el('in').value = DEMO; },
    actions: {
      svg: function(){ if(last) UI.downloadSVG('michaelis-menten.svg', last.spec); },
      png: function(){ if(last) UI.downloadPNG('michaelis-menten.png', last.spec); },
      csv: function(){ if(!last) return; var f = last.fit;
        UI.downloadText('michaelis-menten-results.csv', UI.csv([['parameter', 'estimate', 'se', 'ci95_low', 'ci95_high', 'unit'],
          ['Vmax', f.Vmax, f.se[0], f.ci[0][0], f.ci[0][1], last.vu], ['Km', f.Km, f.se[1], f.ci[1][0], f.ci[1][1], last.su],
          ['R2', f.r2, '', '', '', ''], ['n', f.n, '', '', '', ''], ['left_out', last.d.xS.length, '', '', '', '']]), 'text/csv'); },
      r: function(){ if(last) UI.downloadText('michaelis-menten.R', rscript(last.d, last.su, last.vu)); }
    } });
})();
